"""V10 independent release checks. No external network or secrets required."""
import json, re, subprocess
from pathlib import Path
from bs4 import BeautifulSoup
import tinycss2
root=Path(__file__).resolve().parents[1]
web=root/'webstudio'
ops_html=(web/'ops-check.html').read_text(encoding='utf-8')
ops_js=(web/'assets/ops-check.js').read_text(encoding='utf-8')
ops_css=(web/'assets/ops-check.css').read_text(encoding='utf-8')
admin_html=(web/'admin-inbox.html').read_text(encoding='utf-8')
admin_js=(web/'assets/admin-inbox.js').read_text(encoding='utf-8')
h=BeautifulSoup(ops_html,'html.parser')
a=BeautifulSoup(admin_html,'html.parser')
checks=[]
def t(label,cond):
    checks.append({'name':label,'pass':bool(cond)})
    if not cond: raise AssertionError(label)

t('HTML lang ko',h.html.get('lang')=='ko')
t('HTML charset',bool(h.find('meta',attrs={'charset':'utf-8'})))
t('viewport responsive',bool(h.find('meta',attrs={'name':'viewport'})))
t('operator page noindex','noindex' in h.find('meta',attrs={'name':'robots'})['content'])
t('operator page noarchive','noarchive' in h.find('meta',attrs={'name':'robots'})['content'])
t('operator page no referrer',bool(h.find('meta',attrs={'name':'referrer','content':'no-referrer'})))
t('no external JS origin',all(script.get('src','').startswith('assets/') for script in h.find_all('script')))
t('no inline script',all(not s.text.strip() for s in h.find_all('script')))
t('external css local',all(link.get('href','').startswith('assets/') for link in h.find_all('link',rel='stylesheet')))
t('unique IDs',len({tag.get('id') for tag in h.find_all(attrs={'id':True})})==len(h.find_all(attrs={'id':True})))
t('skip navigation',bool(h.find('a',href='#main')))
t('main element exists',bool(h.find('main',id='main')))
t('status live region',bool(h.find(id='activity',attrs={'aria-live':'polite'})))
t('summary live region',bool(h.find(id='summary',attrs={'aria-live':'polite'})))
t('download disabled until checked',h.find(id='download-check').has_attr('disabled'))
t('no public password input',len(h.select('input[type=password]'))==0)
t('no personal data form',len(h.find_all('form'))==0)
t('mailto correct',any('nineeyes@naver.com' in x.get('href','') for x in h.find_all('a',href=True)))
t('Cloudflare D1 docs linked',any('developers.cloudflare.com/d1/' in x.get('href','') for x in h.find_all('a',href=True)))
t('Cloudflare bindings docs linked',any('/pages/functions/bindings/' in x.get('href','') for x in h.find_all('a',href=True)))
t('Cloudflare Turnstile docs linked',any('/turnstile/get-started/' in x.get('href','') for x in h.find_all('a',href=True)))
t('external links noopener',all('noopener' in x.get('rel',[]) for x in h.find_all('a',href=True) if x.get('target')=='_blank'))
t('named D1 binding', 'INQUIRIES_DB' in ops_html)
t('secret names but no values','STUDIO_ADMIN_TOKEN' in ops_html and not re.search(r'STUDIO_ADMIN_TOKEN\s*[=:]\s*[A-Za-z0-9_-]{43,}',ops_html))
t('public flag names','PUBLIC_INBOX_ENABLED=1' in ops_html and 'PRIVACY_POLICY_APPROVED=1' in ops_html)
t('no paid SDK linked',not any('cdn.jsdelivr' in x.get('src','') for x in h.find_all('script')))
t('ops js no innerHTML',not re.search(r'\b(?:innerHTML|outerHTML)\b',ops_js))
t('ops js no eval',not re.search(r'\beval\s*\(',ops_js))
t('ops js uses textContent','textContent' in ops_js)
t('ops js requests GET only',"method:'GET'" in ops_js and "method:'POST'" not in ops_js)
t('no credentials in ops fetch',"credentials:'omit'" in ops_js)
t('no response body read for admin unauthorized',"if (response.status===401 || response.status===503)" in ops_js)
t('admin auth 200 flagged',"if(response.status===200)" in ops_js)
t('method 405 checked','response.status===405' in ops_js)
t('D1 not configured class warning',"result?.ready===false" in ops_js)
t('no claim ready alone is E2E','실제 저장 시험은 별도로' in ops_js)
t('timeout set', '9500' in ops_js and 'AbortController' in ops_js)
t('downloads BOM TXT',"'\\uFEFF'" in ops_js and 'text/plain' in ops_js)
t('ops JS no localStorage',not re.search(r'localStorage|sessionStorage',ops_js))
t('ops export sanitized', 'latest.checks.forEach' in ops_js and 'const lines' in ops_js)
t('ops reduced motion', '@media(prefers-reduced-motion:reduce)' in ops_css)
t('ops mobile 320 support', '@media(max-width:450px)' in ops_css)
t('focus visible', ':focus-visible' in ops_css)
t('status badge styles', '.check[data-status=fail]' in ops_css)
t('admin noindex','noindex' in a.find('meta',attrs={'name':'robots'})['content'])
t('admin diagnostics entry',bool(a.select_one('a[href="ops-check.html"]')))
t('admin idle lock notice','15분간 활동이 없으면' in admin_html)
t('admin idle 15 minutes','15 * 60 * 1000' in admin_js)
t('admin clears token on lock',"token=''; rows=[];" in admin_js)
t('admin clears PII DOM','container.replaceChildren()' in admin_js)
t('admin password cleared',"$('admin-token').value=''" in admin_js)
t('admin no credentials persisted','localStorage' not in admin_js and 'sessionStorage' not in admin_js)
t('admin CSV injection protection',r"\u0000-\u001f" in admin_js and "v=\"'\"+v" in admin_js)
t('V9 base routes exact',json.loads((Path('/mnt/data/Allfileone_WebStudio_V9_20261107/webstudio/_routes.json')).read_text())=={'version':1,'include':['/api/*'],'exclude':[]})
for path in [web/'assets/ops-check.js',web/'assets/admin-inbox.js']:
    t('node syntax '+path.name,subprocess.run(['node','--check',str(path)],capture_output=True).returncode==0)
css_errors=[]
for rule in tinycss2.parse_stylesheet(ops_css,skip_comments=True,skip_whitespace=True):
    if rule.type=='error':css_errors.append(str(rule))
t('CSS parser no errors',not css_errors)
report={'passed':sum(x['pass'] for x in checks),'failed':sum(not x['pass'] for x in checks),'checks':checks,'method':'local static HTML, CSS, JavaScript checks'}
(root/'qa/V10_STATIC_RESULTS.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'passed':report['passed'],'failed':report['failed'],'css_errors':css_errors},ensure_ascii=False))
