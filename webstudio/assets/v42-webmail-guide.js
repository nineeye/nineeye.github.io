/* AllFileOne WebStudio V42 — extra no-cost webmail handoff.
 * No data is sent to the network, saved, tracked, or submitted.
 * Actual email delivery is ONLY done by a person pressing Send in their own mail app.
 */
'use strict';
(() => {
  function init() {
    const base = document.getElementById('v40-mail-fallback');
    const form = document.getElementById('brief-form');
    const preview = document.getElementById('brief-output');
    if (!base || !form || !preview || document.getElementById('v42-webmail-guide')) return;

    const panel = document.createElement('div');
    panel.id = 'v42-webmail-guide';
    panel.className = 'v42-webmail-guide';
    panel.setAttribute('aria-label', '웹메일로 제작 문의 보내기');

    const heading = document.createElement('strong');
    heading.className = 'v42-webmail-heading';
    heading.textContent = '메일 앱이 없어도 상담 내용을 보낼 수 있습니다';

    const steps = document.createElement('p');
    steps.className = 'v42-webmail-steps';
    steps.textContent = '① 위에서 받는 사람 주소 복사 → ② 웹메일 새 메일의 받는 사람 칸에 붙여넣기 → ③ 아래에서 제목·요청서를 복사해 붙여넣고 직접 보내기';

    const controls = document.createElement('div');
    controls.className = 'v42-webmail-controls';

    const copyBrief = document.createElement('button');
    copyBrief.id = 'v42-copy-complete';
    copyBrief.type = 'button';
    copyBrief.className = 'v42-copy-complete';
    copyBrief.textContent = '제목·상담 요청서 함께 복사';

    const openWebmail = document.createElement('a');
    openWebmail.id = 'v42-open-webmail';
    openWebmail.className = 'v42-open-webmail';
    openWebmail.href = 'https://mail.naver.com/';
    openWebmail.target = '_blank';
    openWebmail.rel = 'noopener noreferrer';
    openWebmail.textContent = '네이버 메일 열기 ↗';

    const result = document.createElement('p');
    result.id = 'v42-copy-feedback';
    result.className = 'v42-copy-feedback';
    result.setAttribute('role', 'status');
    result.setAttribute('aria-live', 'polite');

    const caution = document.createElement('p');
    caution.className = 'v42-webmail-disclaimer';
    caution.textContent = '주소 복사나 초안 복사만으로는 상담이 접수되지 않습니다. 사용 중인 메일 서비스의 보내기 버튼을 직접 눌러야 실제 발송됩니다.';

    controls.append(copyBrief, openWebmail);
    panel.append(heading, steps, controls, result, caution);
    base.append(panel);

    copyBrief.addEventListener('click', async () => {
      if (!form.checkValidity()) {
        result.textContent = '업종과 제작 목적을 선택한 뒤 복사해 주세요. 아직 이메일은 발송되지 않았습니다.';
        if (typeof form.reportValidity === 'function') form.reportValidity();
        return;
      }
      // Preview text is generated by existing V26/V39 code, which allows only
      // known plan/industry/module values and includes all selected functionality.
      const body = preview.textContent.trim();
      if (!body || body.length > 20000) {
        result.textContent = '요청서 내용을 확인해 주세요. 자동 발송되지 않았습니다.';
        return;
      }
      const sel = form.elements.namedItem('industry');
      const industry = sel?.selectedOptions?.[0]?.textContent.trim().slice(0, 80) || '맞춤형';
      const subject = `[올파일원 웹스튜디오] ${industry} 홈페이지 제작 문의`;
      const message = `제목: ${subject}\n\n${body}`;
      try {
        if (typeof navigator.clipboard?.writeText !== 'function') throw new Error('Clipboard unavailable');
        await navigator.clipboard.writeText(message);
        result.textContent = '제목과 요청서 내용을 복사했습니다. 이메일 주소를 받는 사람에 입력하고 웹메일에서 직접 전송해 주세요. 아직 발송되지 않았습니다.';
      } catch {
        result.textContent = '브라우저가 자동 복사를 제한했습니다. 위의 요청서 미리보기에서 직접 선택하거나 TXT 저장 기능을 사용해 주세요. 아직 발송되지 않았습니다.';
      }
    });
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init, {once:true});
  else init();
})();
